# Description=Biometric Authentication Server
# After=network-online.target
# Wants=network-online.target
#
# [Service]
# WorkingDirectory=$SCRIPT_DIR
# ExecStart=$PYTHON $SCRIPT_DIR/server.py
# Restart=always
# RestartSec=5
# StandardOutput=journal
# StandardError=journal
#
# [Install]
# WantedBy=multi-user.target
# SERVICE
# systemctl daemon-reload
# systemctl enable biometric.service
# systemctl start  biometric.service
# ok "Systemd service installed and started."

echo ""
echo -e "${GREEN}══════════════════════════════════════════════${NC}"
echo -e "${GREEN}  Installation complete.                       ${NC}"
echo -e "${GREEN}  Start server:  ./run_server.sh               ${NC}"
echo -e "${GREEN}  Or directly:   python3 server.py             ${NC}"
echo -e "${GREEN}══════════════════════════════════════════════${NC}"
